import os
import json
import time
import inspect
import sys

from ai_ml.brain.ga_config import GAConfig
from ai_ml.brain.physics_filter import PhysicsFilter
from ai_ml.brain.reasoning_generator import ReasoningGenerator
from ai_ml.brain.pso_optimizer import PSOOptimizer
from ai_ml.brain.esm2_scorer import ESM2Scorer
from ai_ml.brain.ranker import Ranker
from ai_ml.brain.sequence_loader import SequenceLoader
from ai_ml.brain.causal_graph_loader import CausalGraphLoader


class InferenceEngine:
    def __init__(self):
        print("Initializing AETHER Inference Engine...")
        self.config = GAConfig()
        self.physics_filter = PhysicsFilter()
        self.scorer = None  # Will instantiate when we have wild_type

        # Dynamically trigger causal graph loader resolution
        print("Verifying causal graph registry...")
        causal_loader = CausalGraphLoader()
        causal_loader.resolve_causal_positions()

    def _load_causal_positions(self) -> list[int]:
        """Dynamically loads the causal positions generated by DoWhy."""
        cache_path = os.path.join(
            os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
            "models",
            "causal_positions.json"
        )
        try:
            with open(cache_path, "r") as f:
                targets = json.load(f)
            print(f"Loaded {len(targets)} causal positions from graph.")
            return targets
        except (FileNotFoundError, json.JSONDecodeError):
            fallback_targets = [3, 5, 8, 12, 18, 25]
            print(f"WARNING: causal_positions.json not found. Using fallback targets: {fallback_targets}")
            return fallback_targets

    def run(self, wild_type_sequence: str) -> str:
        print("\n--- RUNNING FULL PIPELINE TEST ---")
        start_time = time.time()

        # 1. Load Real Causal Targets
        raw_targets = self._load_causal_positions()

        # BIOINFORMATICS SAFETY CHECK:
        # Filter out any positions that are out of bounds for the current sequence.
        # This prevents crashes if PDB numbering doesn't match the FASTA length.
        targets = [pos for pos in raw_targets if pos < len(wild_type_sequence)]

        print(f"Loaded {len(raw_targets)} raw positions. Filtered down to {len(targets)} valid targets.")
        print(f"Using causal positions: {targets}")

        # 2. Score Wild-Type baseline
        print("Scoring Wild-Type baseline...")
        if not self.scorer:
            self.scorer = ESM2Scorer(wild_type_sequence=wild_type_sequence)

        wt_score = self.scorer._raw_log_prob(wild_type_sequence)
        print(f"Wild-Type baseline score: {wt_score:.6f}")

        # 3. Ignite GA+PSO Swarm (Passing shared modules safely to conserve RAM)
        print("Igniting GA+PSO Swarm...")

        # Verify downstream initialization signature compatibility of the optimizer
        pso_params = inspect.signature(PSOOptimizer.__init__).parameters
        pso_kwargs = {"wild_type": wild_type_sequence}
        if "scorer" in pso_params:
            pso_kwargs["scorer"] = self.scorer
        if "physics_filter" in pso_params:
            pso_kwargs["physics_filter"] = self.physics_filter

        pso = PSOOptimizer(self.config, targets, **pso_kwargs)
        final_population = pso.optimize(wild_type_sequence)

        print("Ranking candidates and generating reasoning...")

        # 4. Convert PSO dict output to ranker tuple format and extract mutations
        converted_population = []
        for item in final_population:
            seq = item['sequence']
            score = float(item['score'])
            
            # Extract mutations by comparing to wild-type
            mutations = [
                f"{wild_type_sequence[j]}{j+1}{seq[j]}"
                for j in range(len(seq))
                if j < len(wild_type_sequence) 
                and seq[j] != wild_type_sequence[j]
            ]
            
            converted_population.append((seq, score, mutations))

        population_with_mutations = converted_population

        # 5. Rank Top 10
        ranker = Ranker(wt_score, wild_type_sequence=wild_type_sequence)
        ranked_candidates = ranker.rank_candidates(population_with_mutations)

        # 6. Generate Reasoning Cards
        reasoner = ReasoningGenerator(wild_type_sequence, targets)
        final_output = reasoner.generate_cards(ranked_candidates)

        end_time = time.time()

        # 7. Count actual generations run from PSO
        generations_run = getattr(pso, 'generations_completed', self.config.generations)

        # 8. Build Final Payload
        payload = {
            "candidates": final_output,
            "wildtype_rate_baseline": 1.0,
            "disclaimer": (
                "Predicted activity scores are computed as relative evolutionary probability deltas "
                "scaled against reference deep mutational scanning (DMS) datasets. These values represent "
                "scoring benchmarks; absolute kinetic catalytic rates (kcat/Km) require in-vitro "
                "experimental validation."
            ),
            "run_metadata": {
                "generations_run": generations_run,
                "swarm_size": self.config.swarm_size,
                "causal_positions_used": len(targets),
                "execution_time_seconds": round(end_time - start_time, 2)
            }
        }

        return json.dumps(payload, indent=2)


